-- V2: M1 identity, user security, and role relationship updates

-- 1. Add automatic ID generation to M1 primary keys.

ALTER TABLE monolith."user"
    ALTER COLUMN user_id
    ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE monolith.app_role
    ALTER COLUMN role_id
    ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE monolith.user_role
    ALTER COLUMN user_role_id
    ADD GENERATED BY DEFAULT AS IDENTITY;

-- Synchronize identity sequences with existing records.

SELECT setval(
    pg_get_serial_sequence('monolith."user"', 'user_id'),
    COALESCE(MAX(user_id), 1),
    COUNT(*) > 0
)
FROM monolith."user";

SELECT setval(
    pg_get_serial_sequence('monolith.app_role', 'role_id'),
    COALESCE(MAX(role_id), 1),
    COUNT(*) > 0
)
FROM monolith.app_role;

SELECT setval(
    pg_get_serial_sequence('monolith.user_role', 'user_role_id'),
    COALESCE(MAX(user_role_id), 1),
    COUNT(*) > 0
)
FROM monolith.user_role;


-- 2. Enforce a consistent account status.

UPDATE monolith."user"
SET is_active = TRUE
WHERE is_active IS NULL;

ALTER TABLE monolith."user"
    ALTER COLUMN is_active SET DEFAULT TRUE,
    ALTER COLUMN is_active SET NOT NULL;


-- 3. Add login security tracking.

ALTER TABLE monolith."user"
    ADD COLUMN failed_login_attempts INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN locked_until TIMESTAMPTZ,
    ADD COLUMN last_login_at TIMESTAMPTZ;

ALTER TABLE monolith."user"
    ADD CONSTRAINT ck_user_failed_login_attempts_nonnegative
    CHECK (failed_login_attempts >= 0);


-- 4. Enforce case-insensitive email uniqueness.

CREATE UNIQUE INDEX uq_user_email_lower
    ON monolith."user" (LOWER(BTRIM(email)));


-- 5. Correct the user-role relationship.

-- A user can have only one role.
-- A role can be assigned to many users.

ALTER TABLE monolith.user_role
    DROP CONSTRAINT uq_role_id;

ALTER TABLE monolith.user_role
    ALTER COLUMN user_id SET NOT NULL,
    ALTER COLUMN role_id SET NOT NULL;


-- 6. Seed the standard LMS roles.

INSERT INTO monolith.app_role (name)
VALUES
    ('ADMIN'),
    ('TRAINER'),
    ('LEARNER')
ON CONFLICT (name) DO NOTHING;