BEGIN;
CREATE SCHEMA IF NOT EXISTS monolith;

CREATE TABLE monolith.app_role (
    role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE monolith."user" (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    email varchar(155) NOT NULL UNIQUE,
    password_hash varchar NOT NULL,
    first_name varchar(40) NOT NULL,
    last_name varchar(40) NOT NULL,
    phone varchar(15),
    is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE monolith.user_role (
    user_role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    user_id bigint NOT NULL REFERENCES monolith."user"(user_id),
    role_id bigint NOT NULL REFERENCES monolith.app_role(role_id),
    UNIQUE (user_id, role_id)
);
CREATE TABLE monolith.category (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    name varchar NOT NULL UNIQUE,
    description varchar
);
CREATE TABLE monolith.course (
    course_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    trainer_id bigint NOT NULL REFERENCES monolith."user"(user_id),
    category_id bigint REFERENCES monolith.category(category_id),
    name varchar(155) NOT NULL,
    description varchar,
    status varchar NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE monolith.course_module (
    module_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    course_id bigint NOT NULL REFERENCES monolith.course(course_id),
    title varchar(50) NOT NULL,
    description varchar,
    "position" bigint NOT NULL CHECK ("position" > 0),
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE (course_id, "position") DEFERRABLE INITIALLY IMMEDIATE
);
CREATE TABLE monolith.lesson (
    lesson_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    module_id bigint NOT NULL REFERENCES monolith.course_module(module_id),
    title varchar NOT NULL,
    content varchar,
    lesson_type varchar NOT NULL,
    "position" bigint NOT NULL CHECK ("position" > 0),
    is_required boolean NOT NULL DEFAULT true,
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE (module_id, "position") DEFERRABLE INITIALLY IMMEDIATE
);
CREATE TABLE monolith.enrollment (
    enrollment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    user_id bigint NOT NULL REFERENCES monolith."user"(user_id),
    course_id bigint NOT NULL REFERENCES monolith.course(course_id),
    status varchar NOT NULL,
    enrolled_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,
    UNIQUE (user_id, course_id),
    CHECK (completed_at >= enrolled_at)
);
CREATE TABLE monolith.lesson_progress (
    progress_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    enrollment_id bigint NOT NULL REFERENCES monolith.enrollment(enrollment_id),
    lesson_id bigint NOT NULL REFERENCES monolith.lesson(lesson_id),
    status varchar NOT NULL,
    started_at timestamptz,
    completed_at timestamptz,
    UNIQUE (enrollment_id, lesson_id),
    CHECK (completed_at IS NULL OR (started_at IS NOT NULL AND completed_at >= started_at))
);
CREATE TABLE monolith.lesson_resource (
    resource_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    lesson_id bigint NOT NULL REFERENCES monolith.lesson(lesson_id),
    title varchar NOT NULL,
    resource_type varchar NOT NULL,
    resource_url varchar NOT NULL,
    "position" bigint NOT NULL CHECK ("position" > 0),
    UNIQUE (lesson_id, "position") DEFERRABLE INITIALLY IMMEDIATE
);
CREATE TABLE monolith.assessment (
    assessment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    course_id bigint NOT NULL REFERENCES monolith.course(course_id),
    title varchar NOT NULL,
    passing_score bigint NOT NULL CHECK (passing_score BETWEEN 0 AND 100),
    max_attempts bigint NOT NULL CHECK (max_attempts > 0)
);
CREATE TABLE monolith.attempt (
    attempt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    assessment_id bigint NOT NULL REFERENCES monolith.assessment(assessment_id),
    user_id bigint NOT NULL REFERENCES monolith."user"(user_id),
    score bigint CHECK (score BETWEEN 0 AND 100),
    status varchar NOT NULL,
    submitted_at timestamptz
);
CREATE TABLE monolith.question (
    question_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    assessment_id bigint NOT NULL REFERENCES monolith.assessment(assessment_id),
    prompt varchar NOT NULL,
    points bigint NOT NULL CHECK (points > 0),
    "position" bigint NOT NULL CHECK ("position" > 0),
    UNIQUE (assessment_id, "position") DEFERRABLE INITIALLY IMMEDIATE
);
CREATE TABLE monolith.question_option (
    option_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    question_id bigint NOT NULL REFERENCES monolith.question(question_id),
    option_text varchar NOT NULL,
    is_correct boolean NOT NULL DEFAULT false,
    "position" bigint NOT NULL CHECK ("position" > 0),
    UNIQUE (question_id, "position") DEFERRABLE INITIALLY IMMEDIATE,
    UNIQUE (question_id, option_id)
);
CREATE TABLE monolith.attempt_answer (
    answer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    attempt_id bigint NOT NULL REFERENCES monolith.attempt(attempt_id),
    question_id bigint NOT NULL REFERENCES monolith.question(question_id),
    selected_option_id bigint NOT NULL,
    FOREIGN KEY (question_id, selected_option_id) REFERENCES monolith.question_option(question_id, option_id),
    UNIQUE (attempt_id, question_id)
);
CREATE TABLE monolith.review (
    review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    enrollment_id bigint NOT NULL UNIQUE REFERENCES monolith.enrollment(enrollment_id),
    rating bigint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment varchar
);
CREATE TABLE monolith.notification (
    notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    recipient_id bigint NOT NULL REFERENCES monolith."user"(user_id),
    title varchar NOT NULL,
    message varchar NOT NULL,
    notification_type varchar NOT NULL,
    is_read boolean NOT NULL DEFAULT false,
    read_at timestamptz
);

CREATE INDEX idx_user_role_role ON monolith.user_role(role_id);
CREATE INDEX idx_course_trainer ON monolith.course(trainer_id);
CREATE INDEX idx_course_category ON monolith.course(category_id);
CREATE INDEX idx_enrollment_course ON monolith.enrollment(course_id);
CREATE INDEX idx_progress_lesson ON monolith.lesson_progress(lesson_id);
CREATE INDEX idx_assessment_course ON monolith.assessment(course_id);
CREATE INDEX idx_attempt_assessment ON monolith.attempt(assessment_id);
CREATE INDEX idx_attempt_user ON monolith.attempt(user_id);
CREATE INDEX idx_answer_option ON monolith.attempt_answer(question_id, selected_option_id);
CREATE INDEX idx_notification_recipient ON monolith.notification(recipient_id);

CREATE FUNCTION monolith.set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.app_role
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith."user"
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.user_role
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.category
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.course
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.course_module
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.lesson
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.enrollment
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.lesson_progress
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.lesson_resource
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.assessment
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.attempt
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.question
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.question_option
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.attempt_answer
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.review
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON monolith.notification
    FOR EACH ROW EXECUTE FUNCTION monolith.set_updated_at();

COMMIT;
